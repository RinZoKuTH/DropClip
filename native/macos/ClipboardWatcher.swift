import Foundation
import AppKit

/// macOS Native Clipboard Watcher using Adaptive Polling (PROTO-DC-V2.0 §14.1, FR-03A)
///
/// Poll interval (§16 `MACOS_POLL_ACTIVE/IDLE/LOCKED`): 200 ms while the user had input in the
/// last 30 s, 1,000 ms when idle, 2,000 ms while the screen is locked.
public class ClipboardWatcher {
    private static let activeInterval: TimeInterval = 0.2
    private static let idleInterval: TimeInterval = 1.0
    private static let lockedInterval: TimeInterval = 2.0
    private static let activeWindow: TimeInterval = 30

    // PROTO §10.4 macOS markers: never read content when any of these is present.
    private static let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    private var lastChangeCount: Int
    private var isRunning: Bool = false
    private var isScreenLocked: Bool = false
    private var timer: Timer?
    private var lockObservers: [NSObjectProtocol] = []

    public init() {
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    public func startWatching(onChanged: @escaping (Bool, [String: Data]) -> Void) {
        guard !isRunning else { return }
        isRunning = true
        observeScreenLock()
        scheduleNextPoll(onChanged: onChanged)
    }

    public func stopWatching() {
        isRunning = false
        timer?.invalidate()
        timer = nil
        let center = DistributedNotificationCenter.default()
        lockObservers.forEach { center.removeObserver($0) }
        lockObservers.removeAll()
    }

    private func observeScreenLock() {
        let center = DistributedNotificationCenter.default()
        lockObservers = [
            center.addObserver(forName: NSNotification.Name("com.apple.screenIsLocked"), object: nil, queue: .main) { [weak self] _ in
                self?.isScreenLocked = true
            },
            center.addObserver(forName: NSNotification.Name("com.apple.screenIsUnlocked"), object: nil, queue: .main) { [weak self] _ in
                self?.isScreenLocked = false
            },
        ]
    }

    private func currentInterval() -> TimeInterval {
        if isScreenLocked { return Self.lockedInterval }
        // kCGAnyInputEventType: seconds since the last keyboard/mouse event in this session.
        let idle = CGEventSource.secondsSinceLastEventType(
            .combinedSessionState,
            eventType: CGEventType(rawValue: ~0)!
        )
        return idle < Self.activeWindow ? Self.activeInterval : Self.idleInterval
    }

    // One-shot timer re-armed after every poll so the interval can adapt.
    private func scheduleNextPoll(onChanged: @escaping (Bool, [String: Data]) -> Void) {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: currentInterval(), repeats: false) { [weak self] _ in
            guard let self = self, self.isRunning else { return }
            let currentCount = NSPasteboard.general.changeCount
            if currentCount != self.lastChangeCount {
                self.lastChangeCount = currentCount
                self.handleClipboardChange(onChanged: onChanged)
            }
            self.scheduleNextPoll(onChanged: onChanged)
        }
    }

    private func handleClipboardChange(onChanged: @escaping (Bool, [String: Data]) -> Void) {
        let pasteboard = NSPasteboard.general
        let types = pasteboard.types ?? []

        // FR-05 Sensitive filtering
        if types.contains(where: { Self.concealedTypes.contains($0) }) {
            onChanged(true, [:]) // Do not read content for concealed data
            return
        }

        var items: [String: Data] = [:]
        if let text = pasteboard.string(forType: .string) {
            items["text/plain"] = text.data(using: .utf8)
        }
        if let pngData = pasteboard.data(forType: .png) {
            items["image/png"] = pngData
        } else if let tiffData = pasteboard.data(forType: .tiff) {
            items["image/tiff"] = tiffData
        }

        onChanged(false, items)
    }
}
